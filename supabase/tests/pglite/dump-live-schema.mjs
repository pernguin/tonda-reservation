// Regenerates live-schema.sql from the linked Supabase project's catalog (read-only queries, no Docker).
// Usage: npm run test:sql:dump   (needs the Supabase CLI logged in and the repo linked)
// Run it after `supabase db push` so the snapshot includes the migrations just applied.
import { execSync } from 'node:child_process'
import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '../../..')

const out = execSync('npx supabase db query --linked -f supabase/tests/pglite/dump-live-schema.sql', {
  cwd: repoRoot,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
})
const { rows } = JSON.parse(out.slice(out.indexOf('{')))
if (!rows?.length) throw new Error('dump query returned no rows')

const through = rows[0].migrations_through
const sql = [
  '-- Generated by dump-live-schema.mjs from the live catalog. Do not edit; rerun `npm run test:sql:dump`.',
  `-- migrations-through: ${through}`,
  '',
  'set check_function_bodies = off;',
  '',
  ...rows.map((r) => r.stmt + '\n'),
].join('\n')

await writeFile(resolve(here, 'live-schema.sql'), sql)
console.log(`live-schema.sql: ${rows.length} statements, migrations through ${through}`)
