-- Rebuilds the live `public` schema as SQL from the catalog (read-only). Run by dump-live-schema.mjs.
-- Returns one row per statement, in the order they must run.
with
pub_tables as (
  select c.oid, c.relname, format('public.%I', c.relname) as qname, c.relrowsecurity, c.relforcerowsecurity, c.relacl, c.relkind
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p')
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
pub_funcs as (
  select p.oid, p.proname, p.prokind, p.proacl, p.proowner,
    format('public.%I(%s)', p.proname, pg_get_function_identity_arguments(p.oid)) as sig
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
api_roles(rolname) as (values ('anon'), ('authenticated'), ('service_role')),
stmts(ord, sub, stmt) as (
  -- 1. sequences
  select 10, c.relname::text, format('create sequence public.%I;', c.relname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
  union all
  -- 2. enum types
  select 20, t.typname::text, format('create type public.%I as enum (%s);', t.typname,
    (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid))
  from pg_type t join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'
  union all
  -- 3. tables (columns, defaults, not null, identity, generated)
  select 30, t.relname::text, format(E'create table %s (\n%s\n);', t.qname, (
    select string_agg(
      format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
      || case when a.attidentity = 'a' then ' generated always as identity'
              when a.attidentity = 'd' then ' generated by default as identity' else '' end
      || case when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(ad.adbin, ad.adrelid))
              when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
      || case when a.attnotnull then ' not null' else '' end,
      E',\n' order by a.attnum)
    from pg_attribute a
    left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
    where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from pub_tables t
  union all
  -- 4. sequence ownership
  select 40, c.relname::text, format('alter sequence public.%I owned by %s.%I;', c.relname, t.qname, a.attname)
  from pg_class c
  join pg_depend d on d.objid = c.oid and d.deptype in ('a', 'i') and d.refobjsubid > 0
  join pub_tables t on t.oid = d.refobjid
  join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
  where c.relkind = 'S' and not exists (select 1 from pg_attribute x where x.attrelid = t.oid and x.attidentity <> '' and x.attnum = d.refobjsubid)
  union all
  -- 5. constraints: primary/unique/check/exclusion first, foreign keys after every table exists
  select case when con.contype = 'f' then 60 else 50 end, t.relname || '.' || con.conname,
    format('alter table only %s add constraint %I %s;', t.qname, con.conname, pg_get_constraintdef(con.oid))
  from pg_constraint con join pub_tables t on t.oid = con.conrelid
  where con.contype in ('p', 'u', 'c', 'x', 'f')
  union all
  -- 6. indexes that do not back a constraint
  select 70, i.indexrelid::regclass::text, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join pub_tables t on t.oid = i.indrelid
  where not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
  union all
  -- 7. functions and procedures
  select 80, f.sig, pg_get_functiondef(f.oid) || ';'
  from pub_funcs f
  union all
  -- 8. views (after functions; they may call them)
  select 90, c.relname::text, format(E'create view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid))
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
  union all
  -- 9. triggers
  select 100, t.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg join pub_tables t on t.oid = tg.tgrelid
  where not tg.tgisinternal
  union all
  -- 10. row level security
  select 110, t.relname::text, format('alter table %s enable row level security;', t.qname)
  from pub_tables t where t.relrowsecurity
  union all
  select 110, t.relname::text, format('alter table %s force row level security;', t.qname)
  from pub_tables t where t.relforcerowsecurity
  union all
  select 120, t.relname || '.' || pol.polname,
    format('create policy %I on %s as %s for %s to %s%s%s;', pol.polname, t.qname,
      case when pol.polpermissive then 'permissive' else 'restrictive' end,
      case pol.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end,
      coalesce((select string_agg(case when r = 0 then 'public' else quote_ident(pg_get_userbyid(r)) end, ', ')
                from unnest(pol.polroles) r), 'public'),
      coalesce(' using (' || pg_get_expr(pol.polqual, pol.polrelid) || ')', ''),
      coalesce(' with check (' || pg_get_expr(pol.polwithcheck, pol.polrelid) || ')', ''))
  from pg_policy pol join pub_tables t on t.oid = pol.polrelid
  union all
  -- 11. grants to the API roles: tables (and their columns), then functions
  select 130, t.relname::text, format('revoke all on table %s from public, anon, authenticated, service_role;', t.qname)
  from pub_tables t
  union all
  select 131, t.relname || '.' || acl.privilege_type || '.' || r.rolname,
    format('grant %s on table %s to %I;', lower(acl.privilege_type), t.qname, r.rolname)
  from pub_tables t
  cross join lateral aclexplode(t.relacl) acl
  join pg_roles r on r.oid = acl.grantee
  where r.rolname in (select rolname from api_roles)
  union all
  select 132, t.relname || '.' || a.attname || '.' || acl.privilege_type || '.' || r.rolname,
    format('grant %s (%I) on table %s to %I;', lower(acl.privilege_type), a.attname, t.qname, r.rolname)
  from pub_tables t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped and a.attacl is not null
  cross join lateral aclexplode(a.attacl) acl
  join pg_roles r on r.oid = acl.grantee
  where r.rolname in (select rolname from api_roles)
  union all
  select 140, f.sig, format('revoke all on function %s from public, anon, authenticated, service_role;', f.sig)
  from pub_funcs f
  union all
  select 141, f.sig || '.' || coalesce(r.rolname, 'public'),
    format('grant execute on function %s to %s;', f.sig, coalesce(quote_ident(r.rolname), 'public'))
  from pub_funcs f
  cross join lateral aclexplode(coalesce(f.proacl, acldefault('f', f.proowner))) acl
  left join pg_roles r on r.oid = acl.grantee
  where acl.grantee = 0 or r.rolname in (select rolname from api_roles)
  union all
  -- 12. realtime publication membership
  select 150, pt.tablename::text, format('alter publication supabase_realtime add table public.%I;', pt.tablename)
  from pg_publication_tables pt
  where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public'
  union all
  -- 13. cron jobs (pg_cron state the migrations create)
  select 160, j.jobname::text, format('select cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command)
  from cron.job j
)
select ord, sub, stmt,
  (select max(version) from supabase_migrations.schema_migrations) as migrations_through
from stmts
order by ord, sub;
